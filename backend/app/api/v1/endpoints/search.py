"""Search and RAG question-answering endpoints.

Route prefix: /api/v1/search (search)
             /api/v1/ask    (RAG)
"""

import uuid

from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import StreamingResponse

from app.api.deps import get_optional_current_user_id as get_current_user_id, get_search_service
from app.schemas.search import AskRequest, AskResponse, SearchRequest, SearchResponse
from app.services.search_service import SearchService

router = APIRouter(tags=["search"])


@router.post(
    "/search",
    response_model=SearchResponse,
    summary="Search codebase symbols",
    description=(
        "Perform semantic, keyword, or hybrid search across all indexed code symbols. "
        "Results are ranked by relevance score and include file path, line numbers, "
        "signature, and docstring context."
    ),
    responses={
        200: {"description": "Ranked search results"},
        401: {"description": "Not authenticated"},
        422: {"description": "Validation error"},
    },
)
async def search_symbols(
    request: SearchRequest,
    _: uuid.UUID | None = Depends(get_current_user_id),
    service: SearchService = Depends(get_search_service),
) -> SearchResponse:
    """Search for code symbols matching the query.

    Args:
        request: Search parameters including query, filters, and mode.
        _: Authenticated user UUID (access guard).
        service: Injected SearchService.

    Returns:
        SearchResponse with ranked SearchHit items.
    """
    try:
        return await service.search(request)
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Search failed: {exc}",
        ) from exc


@router.post(
    "/ask",
    response_model=AskResponse,
    summary="Ask a question about the codebase (RAG)",
    description=(
        "Ask a natural language question about an indexed codebase. "
        "The answer is generated by an LLM grounded in retrieved code context "
        "(symbols, signatures, docstrings) and call-graph relationships from Neo4j.\n\n"
        "Set `stream: false` for a single JSON response. "
        "Set `stream: true` to receive a `text/event-stream` SSE stream."
    ),
    responses={
        200: {"description": "Generated answer with citations"},
        401: {"description": "Not authenticated"},
        422: {"description": "Validation error"},
        503: {"description": "LLM backend unavailable"},
    },
)
async def ask_question(
    request: AskRequest,
    _: uuid.UUID | None = Depends(get_current_user_id),
    service: SearchService = Depends(get_search_service),
) -> AskResponse | StreamingResponse:
    """Generate an LLM answer grounded in retrieved code context.

    Args:
        request: Question, scope filters, and LLM configuration.
        _: Authenticated user UUID (access guard).
        service: Injected SearchService.

    Returns:
        AskResponse (JSON) or StreamingResponse (SSE if stream=True).

    Raises:
        HTTPException 503: If the configured LLM backend is unavailable.
    """
    if request.stream:
        return _stream_ask(request, service)

    try:
        return await service.ask(request)
    except ConnectionError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"LLM backend unavailable: {exc}",
        ) from exc
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"RAG pipeline failed: {exc}",
        ) from exc


def _stream_ask(request: AskRequest, service: SearchService) -> StreamingResponse:
    """Return a Server-Sent Events streaming response for the RAG answer.

    The stream emits:
      - ``data: <text fragment>`` events for each answer chunk.
      - ``data: [DONE]`` as the final event.

    Args:
        request: Validated AskRequest (with stream=True).
        service: Injected SearchService.

    Returns:
        StreamingResponse with ``text/event-stream`` content type.
    """
    import asyncio
    import json

    async def _generate():
        try:
            response = await service.ask(request)
            words = response.answer.split(" ")
            for i, word in enumerate(words):
                chunk = word + (" " if i < len(words) - 1 else "")
                yield f"data: {json.dumps({'text': chunk})}\n\n"
                await asyncio.sleep(0)  # yield control to event loop
            # Send final event with full metadata
            meta = {
                "done": True,
                "model": response.model,
                "took_ms": response.took_ms,
                "tokens_used": response.tokens_used,
                "context_count": len(response.context),
            }
            yield f"data: {json.dumps(meta)}\n\n"
            yield "data: [DONE]\n\n"
        except Exception as exc:
            yield f"data: {json.dumps({'error': str(exc)})}\n\n"
            yield "data: [DONE]\n\n"

    return StreamingResponse(
        _generate(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
        },
    )
